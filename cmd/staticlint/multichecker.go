// Package main реализует многоплановый статический анализатор кода Go.
// Анализатор объединяет стандартные проверки из пакета golang.org/x/tools,
// проверки из Staticcheck (классы SA и ST), а также пользовательские анализаторы.
//
// Запуск анализатора осуществляется через multichecker.Main, который принимает
// список анализаторов и выполняет их последовательно над указанными пакетами.
// Все анализаторы объединяются в единый инструмент, который можно запускать
// как обычную команду с флагами для фильтрации пакетов.
//
// Механизм работы multichecker:
//  1. Регистрируются все переданные анализаторы в едином наборе
//  2. Обрабатываются флаги командной строки (включая флаги самих анализаторов)
//  3. Выполняется анализ всех указанных пакетов (по умолчанию - текущий пакет)
//  4. Результаты анализа выводятся в стандартный поток вывода/ошибок
//  5. В случае ошибок возвращается ненулевой код завершения
//
// Использование:
//
//	go run ./cmd/staticlint -- ./...
package main

import (
	"golang.org/x/tools/go/analysis"
	"golang.org/x/tools/go/analysis/multichecker"
	"golang.org/x/tools/go/analysis/passes/nilfunc"
	"golang.org/x/tools/go/analysis/passes/printf"
	"golang.org/x/tools/go/analysis/passes/shadow"
	"golang.org/x/tools/go/analysis/passes/shift"
	"golang.org/x/tools/go/analysis/passes/structtag"
	"golang.org/x/tools/go/analysis/passes/unusedresult"
	"honnef.co/go/tools/staticcheck"
	"honnef.co/go/tools/stylecheck"
)

// main - точка входа в программу-анализатор.
// Собирает все анализаторы в единый список и запускает multichecker.
//
// Состав анализаторов:
//  1. Стандартные анализаторы из golang.org/x/tools:
//     - printf: проверяет корректность форматных строк в функциях семейства Printf
//     - shadow: обнаруживает переменные, которые перекрывают другие переменные в области видимости
//     - shift: проверяет операции сдвига на возможные ошибки (сдвиг на отрицательное число или больше размера)
//     - structtag: проверяет корректность структурных тегов
//
//  2. Все анализаторы класса SA (Staticcheck):
//     Более 30+ анализаторов, проверяющих различные ошибки и подозрительные места:
//     - SA1xxx: обнаружение ошибок в стандартной библиотеке
//     - SA2xxx: обнаружение ошибок в конкурентном коде
//     - SA3xxx: обнаружение ошибок в работе с памятью
//     - SA4xxx: обнаружение ошибок в логике кода
//     - SA5xxx: обнаружение ошибок в работе с типами
//     - SA6xxx: обнаружение ошибок в производительности
//     - SA9xxx: обнаружение ошибок в тестах
//
//  3. Все анализаторы класса ST (Stylecheck):
//     Проверяют соблюдение стиля кода:
//     - ST1xxx: проверки именования и стиля
//     - ST2xxx: проверки документации
//     - ST3xxx: проверки импортов и структур
//     - ST4xxx: проверки ошибок и паники
//     - ST5xxx: проверки функций и методов
//     - ST6xxx: проверки тестов и бенчмарков
//     - ST7xxx: проверки контекста и каналов
//     - ST8xxx: проверки форматирования
//     - ST9xxx: проверки специфичные для Go
//
//  4. Дополнительные публичные анализаторы:
//     - nilfunc: проверяет бессмысленные сравнения функции с nil
//     - unusedresult: проверяет неиспользованные результаты вызовов (часто ошибки)
//
//  5. Собственный анализатор OsExitInMainAnalyzer:
//     Проверяет, что функция main не содержит вызовов os.Exit,
//     что гарантирует корректное завершение программы.
//
// Все анализаторы выполняются последовательно, каждый получает свой AST и
// может сообщать о найденных проблемах. В случае, если какой-либо анализатор
// находит проблему, multichecker продолжает выполнение остальных проверок
// и в конце возвращает код завершения 1, если были обнаружены проблемы.

func main() {
	var analyzers []*analysis.Analyzer

	analyzers = append(analyzers,
		printf.Analyzer,
		shadow.Analyzer,
		shift.Analyzer,
		structtag.Analyzer,
	)
	for _, v := range staticcheck.Analyzers {
		analyzers = append(analyzers, v.Analyzer)
	}

	for _, v := range stylecheck.Analyzers {
		analyzers = append(analyzers, v.Analyzer)
	}

	analyzers = append(analyzers,
		nilfunc.Analyzer,
		unusedresult.Analyzer,
	)

	analyzers = append(analyzers, OsExitInMainAnalyzer)

	multichecker.Main(analyzers...)
}
